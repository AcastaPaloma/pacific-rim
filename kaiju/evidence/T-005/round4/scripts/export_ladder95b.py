"""T-005 r4 9.5b: speed ladder for the imp 3 start. Runs Tools/GaitOpt/export_reference_v2.py (unchanged) on the FEASIBLE low-Froude strides (the same strides as the imp 2 @v1 rows)
and writes their @v2 rows to Assets/Game/Config/Mech/gait_reference_qp_ladder.json (sorted by Froude); gait_reference_qp.json (the Fr 0.10 row) is restored byte for byte.
Run from the project root: /opt/miniconda3/envs/kaiju/bin/python evidence/T-005/round4/scripts/export_ladder95b.py"""
import json, pathlib, subprocess, sys
ROOT = pathlib.Path.cwd(); MAIN = ROOT / "Assets/Game/Config/Mech/gait_reference_qp.json"; OUT = ROOT / "Assets/Game/Config/Mech/gait_reference_qp_ladder.json"
SRC = ["stride_fr002_lat.json", "stride_fr004_lat.json", "stride_fr006_lat.json"]
keep = MAIN.read_bytes(); rows = []; base = None
try:
    for s in SRC:
        subprocess.run([sys.executable, "Tools/GaitOpt/export_reference_v2.py", f"Tools/GaitOpt/out/{s}"], check=True)
        d = json.loads(MAIN.read_text()); rows += d["rows"]; base = base or d
finally:
    MAIN.write_bytes(keep)
base["rows"] = rows; base["notes"] = "Speed ladder of the imp 3 start (T-005 r4 9.5b, qp_ladder): @v2 rows of the low-Froude strides, generated by evidence/T-005/round4/scripts/export_ladder95b.py with Tools/GaitOpt/export_reference_v2.py; do not edit by hand."
base["source"]["files"] = SRC; base["source"]["verdicts"] = [f"{r['source_file']}: {r['verdict']}, fr {r['fr']}" for r in rows]
OUT.write_text(json.dumps(base, indent=1)); print("wrote", OUT, [(r["fr"], round(r["v"], 2), round(r["step_length_m"], 1)) for r in rows])
