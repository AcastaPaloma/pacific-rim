    /// <summary>
    /// 7x10 bitmap pixel font for the M step of the text ladder (R-122 4.4, T-154c). Same character set and drawing style as the 5x7 <see cref="HudFont"/>
    /// (1 px strokes, upper-case only, square corners with clipped diagonals). Each glyph is 10 rows of 7 bits (bit 6 = leftmost); advance 8 (1 px spacing).
    /// </summary>
    public static class HudFontMedium
    {
        public const int GlyphW = 7, GlyphH = 10, Advance = 8;

        static readonly Dictionary<char, byte[]> Glyphs = Build();

        static void Add(Dictionary<char, byte[]> d, char c, string rows)
        {
            var parts = rows.Split(' ');
            if (parts.Length != GlyphH) throw new InvalidOperationException("medium glyph " + c);
            var b = new byte[GlyphH];
            for (int r = 0; r < GlyphH; r++)
            {
                if (parts[r].Length != GlyphW) throw new InvalidOperationException("medium glyph " + c + " row " + r);
                int v = 0;
                for (int x = 0; x < GlyphW; x++) v = (v << 1) | (parts[r][x] == '#' ? 1 : 0);
                b[r] = (byte)v;
            }
            d[c] = b;
        }

